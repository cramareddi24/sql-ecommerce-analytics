"""
Runs every .sql file in queries/ against data/ecommerce.db and writes the
question, the SQL, and the result to outputs/query_results.md.

Usage:
    python scripts/run_queries.py
"""

import sqlite3
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = ROOT / "data" / "ecommerce.db"
QUERY_DIR = ROOT / "queries"
OUT_PATH = ROOT / "outputs" / "query_results.md"
MAX_ROWS = 20


def question_from(sql: str) -> str:
    for line in sql.splitlines():
        if line.startswith("-- Question:"):
            return line.replace("-- Question:", "").strip()
    return ""


def main() -> None:
    if not DB_PATH.exists():
        subprocess.run([sys.executable, str(ROOT / "scripts" / "build_database.py")], check=True)

    con = sqlite3.connect(DB_PATH)
    lines = ["# Query Results", "", "Generated by `scripts/run_queries.py` against the synthetic `ecommerce.db`.", ""]

    for path in sorted(QUERY_DIR.glob("*.sql")):
        sql = path.read_text()
        df = pd.read_sql_query(sql, con)
        shown = df.head(MAX_ROWS)
        lines += [
            f"## {path.stem}",
            "",
            f"**Question:** {question_from(sql)}",
            "",
            "<details><summary>SQL</summary>",
            "",
            "```sql",
            sql.strip(),
            "```",
            "",
            "</details>",
            "",
            shown.to_markdown(index=False),
            "",
        ]
        if len(df) > MAX_ROWS:
            lines += [f"_Showing {MAX_ROWS} of {len(df)} rows._", ""]
        print(f"{path.name}: {len(df)} rows")

    con.close()
    OUT_PATH.parent.mkdir(exist_ok=True)
    OUT_PATH.write_text("\n".join(lines))
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
